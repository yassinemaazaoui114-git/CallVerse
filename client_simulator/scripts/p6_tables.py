"""Markdown tables for the follow-up (delay-aware + fallback) from results/p6_followup.json -> results/p6_tables.md"""
from common import RESULTS, load_json

DELAYS = ["0-5 min", "5-30 min", "30 min-2 h", "2-8 h", "8 h+"]
M = ["qwen3.5:4b", "phi4-mini:3.8b"]
NICK = {"qwen3.5:4b": "qwen3.5", "phi4-mini:3.8b": "phi4-mini"}


def f(x, d=2):
    return "n/a" if x is None else f"{x:.{d}f}"


def main():
    r = load_json(RESULTS / "p6_followup.json")
    b = load_json(RESULTS / "p3_test3_scores.json")["baseline_csat"]
    S = r["settings"]
    key = {}
    for m in M:
        t = r[m]["delay_aware"]["test"]
        key[m] = {"raw": next(k for k in t if k.startswith("raw")), "before": next(k for k in t if k.startswith("global (Phase 3")),
                  "g400": next(k for k in t if k.startswith("global (") and "Phase 3" not in k),
                  "after": r[m]["delay_aware"]["chosen_on_dev"]}
    q, p = M
    tq, tp = r[q]["delay_aware"]["test"], r[p]["delay_aware"]["test"]
    out = [f"<!-- generated by scripts/p6_tables.py; sizes: {S} -->", "",
           f"Chosen on dev: {NICK[q]} = {key[q]['after']}; {NICK[p]} = {key[p]['after']}.", "",
           "**Mean score per waiting-time bucket on test (real vs simulated)**", "",
           "| Waiting time | n | real | qwen3.5 raw | qwen3.5 before (global map) | **qwen3.5 after (dev-chosen)** | phi4-mini before | **phi4-mini after** |",
           "|---|---|---|---|---|---|---|---|"]
    for d in DELAYS:
        row = tq[key[q]["before"]]["by_delay"][d]
        out.append(f"| {d} | {row['n']} | {f(row['real_mean'])} | {f(tq[key[q]['raw']]['by_delay'][d]['sim_mean'])} | "
                   f"{f(row['sim_mean'])} | **{f(tq[key[q]['after']]['by_delay'][d]['sim_mean'])}** | "
                   f"{f(tp[key[p]['before']]['by_delay'][d]['sim_mean'])} | **{f(tp[key[p]['after']]['by_delay'][d]['sim_mean'])}** |")
    out.append(f"| size-weighted mean gap to real | | | {f(tq[key[q]['raw']]['bucket_gap'], 3)} | {f(tq[key[q]['before']]['bucket_gap'], 3)} | "
               f"**{f(tq[key[q]['after']]['bucket_gap'], 3)}** | {f(tp[key[p]['before']]['bucket_gap'], 3)} | **{f(tp[key[p]['after']]['bucket_gap'], 3)}** |")
    out += ["", "**Overall test metrics (n = 200; integer score = expected score rounded)**", "",
            "| Model, calibration | MAE | Spearman | QWK | Wasserstein | macro-F1 |", "|---|---|---|---|---|---|",
            f"| majority \"always 5\" (baseline) | {f(b['majority']['mae'])} | n/a | {f(b['majority']['qwk'])} | {f(b['majority']['wasserstein'])} | {f(b['majority']['macro_f1'])} |",
            f"| TF-IDF + LR (baseline) | {f(b['tfidf_lr']['mae'])} | {f(b['tfidf_lr']['spearman'])} | {f(b['tfidf_lr']['qwk'])} | {f(b['tfidf_lr']['wasserstein'])} | {f(b['tfidf_lr']['macro_f1'])} |"]
    for m in M:
        t = r[m]["delay_aware"]["test"]
        for lab, k in (("before (Phase 3 global map)", "before"), (f"global map refitted on {S['n_cal_big']} rows (used without `wait_minutes`)", "g400"),
                       ("**after (" + key[m]["after"] + ")**", "after")):
            x = t[key[m][k]]["metrics"]
            out.append(f"| {NICK[m]}, {lab} | {f(x['mae'])} | {f(x['spearman'])} | {f(x['qwk'])} | {f(x['wasserstein'])} | {f(x['macro_f1'])} |")
    out += ["", "Dev selection (size-weighted bucket-mean gap; QWK; MAE):", ""]
    for m in M:
        for k, v in r[m]["delay_aware"]["dev"].items():
            out.append(f"- {NICK[m]} - {k}: gap {f(v['bucket_gap'], 3)}, QWK {f(v['qwk'])}, MAE {f(v['mae'])}")
    out += ["", "Calibration rows per delay bucket: " + str(r[q]["delay_aware"]["cal_rows_per_bucket"]), "",
            "**Fallback (confirmed-licence data only) next to the current calibration**", "",
            "| Test set | Calibration | n | MAE | Spearman | QWK | Wasserstein |", "|---|---|---|---|---|---|---|"]
    for m in M:
        fb = r[m]["fallback"]
        for k, x in fb["olist_test"].items():
            out.append(f"| Olist delivery cards | {NICK[m]} {k} | {x['n']} | {f(x['mae'])} | {f(x['spearman'])} | {f(x['qwk'])} | {f(x['wasserstein'])} |")
    for m in M:
        c = r[m]["fallback"]["on_flipkart_csat_test"]
        for k, x in c["main_calibrations_on_same_rows"].items():
            if k.startswith("global (Phase 3") or k == key[m]["after"]:
                out.append(f"| Flipkart CSAT test | {NICK[m]} current: {k} | {x['n']} | {f(x['mae'])} | {f(x['spearman'])} | {f(x['qwk'])} | {f(x['wasserstein'])} |")
        x = c["metrics"]
        out.append(f"| Flipkart CSAT test | **{NICK[m]} fallback prompt + map** | {x['n']} | {f(x['mae'])} | {f(x['spearman'])} | {f(x['qwk'])} | {f(x['wasserstein'])} |")
    out += ["", "Fallback choices on Olist dev: " + "; ".join(
        f"{NICK[m]}: {r[m]['fallback']['olist_chosen_on_dev']} map, lateness-aware "
        f"{'on' if r[m]['fallback']['olist_dev_lateness_gap']['lateness_aware_enabled'] else 'off'}, valid JSON {f(100 * r[m]['fallback']['valid_json'], 0)}%"
        for m in M)]
    for m in M:
        out.append(f"- {NICK[m]} fallback on CSAT test predicted distribution: {r[m]['fallback']['on_flipkart_csat_test']['metrics']['pred_dist']}; "
                   f"Olist raw distribution: {r[m]['fallback']['olist_test']['raw']['pred_dist']}")
    (RESULTS / "p6_tables.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
