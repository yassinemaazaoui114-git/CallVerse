"""Markdown tables with bootstrap 95% CIs for the large rerun + small-vs-large comparison -> results/p7_tables.md"""
from common import RESULTS, load_json

DELAYS = ["0-5 min", "5-30 min", "30 min-2 h", "2-8 h", "8 h+"]
M = ["qwen3.5:4b", "phi4-mini:3.8b"]
NICK = {"qwen3.5:4b": "qwen3.5", "phi4-mini:3.8b": "phi4-mini"}


def f(x, d=2):
    return "n/a" if x is None else f"{x:.{d}f}"


def fc(x, c, d=2):
    return f"{f(x, d)} [{f(c[0], d)}, {f(c[1], d)}]"


def keys(t):
    return {"raw": next(k for k in t if k.startswith("raw")), "before": next(k for k in t if k.startswith("global (Phase 3")),
            "gL": next(k for k in t if k.startswith("global (") and "Phase 3" not in k)}


def main():
    L = load_json(RESULTS / "p7_large.json")
    P3 = load_json(RESULTS / "p3_test3_scores.json")
    P6 = load_json(RESULTS / "p6_followup.json")
    z = L["sizes"]
    out = [f"<!-- generated by scripts/p7_tables.py from results/p7_large.json; sizes {z}; 95% CIs: bootstrap, {z['bootstrap']} resamples -->", ""]
    # ---- 1. per delay bucket
    tq, tp = L[M[0]]["csat"]["test"], L[M[1]]["csat"]["test"]
    kq, kp = keys(tq), keys(tp)
    aq, ap = L[M[0]]["csat"]["chosen_on_dev"], L[M[1]]["csat"]["chosen_on_dev"]
    out += [f"Chosen on dev ({z['csat_dev']} rows): qwen3.5 = {aq}; phi4-mini = {ap}.", "",
            f"**Mean CSAT per waiting-time bucket on the large test sample (n = {z['csat_test']}), 95% CI in brackets**", "",
            "| Waiting time | n | real | qwen3.5 before (Phase 3 global map) | **qwen3.5 after** | phi4-mini before | **phi4-mini after** |",
            "|---|---|---|---|---|---|---|"]
    for d in DELAYS:
        rb = tq[kq["before"]]["by_bucket"][d]
        g = lambda t, k: t[k]["by_bucket"][d]  # noqa: E731
        out.append(f"| {d} | {rb['n']} | {fc(rb['real_mean'], rb['real_mean_ci'])} | {fc(rb['sim_mean'], rb['sim_mean_ci'])} | "
                   f"**{fc(g(tq, aq)['sim_mean'], g(tq, aq)['sim_mean_ci'])}** | {fc(g(tp, kp['before'])['sim_mean'], g(tp, kp['before'])['sim_mean_ci'])} | "
                   f"**{fc(g(tp, ap)['sim_mean'], g(tp, ap)['sim_mean_ci'])}** |")
    out.append(f"| size-weighted mean gap to real | | | {fc(tq[kq['before']]['bucket_gap'], tq[kq['before']]['bucket_gap_ci'])} | "
               f"**{fc(tq[aq]['bucket_gap'], tq[aq]['bucket_gap_ci'])}** | {fc(tp[kp['before']]['bucket_gap'], tp[kp['before']]['bucket_gap_ci'])} | "
               f"**{fc(tp[ap]['bucket_gap'], tp[ap]['bucket_gap_ci'])}** |")
    # ---- 2. overall CSAT
    b = L["baseline_csat"]
    out += ["", f"**Overall CSAT test (n = {z['csat_test']}; integer score = continuous score rounded)**", "",
            "| Model, calibration | MAE [95% CI] | QWK [95% CI] | Spearman | Wasserstein | macro-F1 | bucket-mean gap [95% CI] |",
            "|---|---|---|---|---|---|---|"]
    for lab, x in (("majority \"always 5\" (baseline)", b["majority"]), ("TF-IDF + LR (baseline)", b["tfidf_lr"])):
        out.append(f"| {lab} | {fc(x['mae'], x['mae_ci'])} | {fc(x['qwk'], x['qwk_ci'])} | {f(x['spearman'])} | {f(x['wasserstein'])} | "
                   f"{f(x['macro_f1'])} | {fc(x['bucket_gap'], x['bucket_gap_ci'])} |")
    for m in M:
        t = L[m]["csat"]["test"]
        k = keys(t)
        ch = L[m]["csat"]["chosen_on_dev"]
        for lab, kk in (("raw v2 (no calibration)", k["raw"]), ("before: Phase 3 global map", k["before"]),
                        (f"global map refitted on {z['csat_cal_natural']} rows (used without `wait_minutes`)", k["gL"]), (f"**after: {ch}**", ch)):
            x = t[kk]
            out.append(f"| {NICK[m]}, {lab} | {fc(x['mae'], x['mae_ci'])} | {fc(x['qwk'], x['qwk_ci'])} | {f(x['spearman'])} | "
                       f"{f(x['wasserstein'])} | {f(x['macro_f1'])} | {fc(x['bucket_gap'], x['bucket_gap_ci'])} |")
    out += ["", "Dev selection (500 rows; size-weighted bucket-mean gap, QWK, MAE):", ""]
    for m in M:
        for k, v in L[m]["csat"]["dev"].items():
            out.append(f"- {NICK[m]} - {k}: gap {f(v['bucket_gap'], 3)}, QWK {f(v['qwk'])}, MAE {f(v['mae'])}")
    out.append("")
    out.append("Calibration rows per delay bucket: " + str(L[M[0]]["csat"]["n_cal_rows_per_bucket"]))
    out.append("Invalid JSON (strict) on all CSAT calls: " + ", ".join(f"{NICK[m]} {100 * L[m]['csat']['invalid_json_rate']:.1f}%" for m in M))
    # ---- 3. CONV
    bc = L["baseline_conv"]
    out += ["", f"**CONV - full USS travel test split (n = {z['conv_test']} dialogues, annotator ratings)**", "",
            "| Model / baseline | MAE [95% CI] | QWK [95% CI] | Spearman | Wasserstein |", "|---|---|---|---|---|"]
    for lab, x in (("majority \"always 3\"", bc["majority"]), ("TF-IDF + LR", bc["tfidf_lr"])):
        out.append(f"| {lab} | {fc(x['mae'], x['mae_ci'])} | {fc(x['qwk'], x['qwk_ci'])} | {f(x['spearman'])} | {f(x['wasserstein'])} |")
    for m in M:
        c = L[m]["conv"]
        for lab, x in (("raw v2", c["raw_v2"]), (f"Phase 3 chosen ({c['chosen_version_phase3']})", c["chosen"])):
            out.append(f"| {NICK[m]}, {lab} | {fc(x['mae'], x['mae_ci'])} | {fc(x['qwk'], x['qwk_ci'])} | {f(x['spearman'])} | {f(x['wasserstein'])} |")
    # ---- 4. fallback
    out += ["", "**Fallback (confirmed-licence data only) next to the current calibration**", "",
            "| Test set | Calibration | n | MAE [95% CI] | QWK [95% CI] | Wasserstein |", "|---|---|---|---|---|---|"]
    for m in M:
        for k, x in L[m]["fallback"]["olist_test"].items():
            out.append(f"| Olist delivery cards | {NICK[m]} {k} | {x['n']} | {fc(x['mae'], x['mae_ci'])} | {fc(x['qwk'], x['qwk_ci'])} | {f(x['wasserstein'])} |")
    for m in M:
        o = L[m]["fallback"]["on_csat_test"]
        for k, x in o["main_on_same_rows"].items():
            out.append(f"| Flipkart CSAT test | {NICK[m]} current: {k} | {x['n']} | {fc(x['mae'], x['mae_ci'])} | {fc(x['qwk'], x['qwk_ci'])} | {f(x['wasserstein'])} |")
        x = o["fallback"]
        out.append(f"| Flipkart CSAT test | **{NICK[m]} fallback prompt + map** | {x['n']} | {fc(x['mae'], x['mae_ci'])} | {fc(x['qwk'], x['qwk_ci'])} | {f(x['wasserstein'])} |")
    out.append("")
    out.append("Fallback choices on Olist dev: " + "; ".join(
        f"{NICK[m]}: {L[m]['fallback']['olist_chosen_on_dev']} map, lateness-aware {'on' if L[m]['fallback']['lateness_dev_gap']['enabled'] else 'off'}, "
        f"valid JSON {100 * L[m]['fallback']['valid_json']:.1f}%" for m in M))
    for m in M:
        out.append(f"- {NICK[m]}: fallback on CSAT predicted distribution {L[m]['fallback']['on_csat_test']['fallback']['pred_dist']}; "
                   f"Olist raw distribution {L[m]['fallback']['olist_test']['raw']['pred_dist']}")
    # ---- 5. small vs large
    out += ["", "**Small vs large samples (same seed; the small samples are prefixes of the large ones)**", "",
            "| Quantity | small: value (n) | large: value [95% CI] (n) |", "|---|---|---|"]
    bs = P3["baseline_csat"]

    def row(lab, sv, sn, lx, lci, ln, d=2):
        out.append(f"| {lab} | {f(sv, d)} ({sn}) | {fc(lx, lci, d)} ({ln}) |")
    row("TF-IDF baseline, CSAT test QWK", bs["tfidf_lr"]["qwk"], bs["tfidf_lr"]["n"], b["tfidf_lr"]["qwk"], b["tfidf_lr"]["qwk_ci"], z["csat_test"])
    row("TF-IDF baseline, CSAT test MAE", bs["tfidf_lr"]["mae"], bs["tfidf_lr"]["n"], b["tfidf_lr"]["mae"], b["tfidf_lr"]["mae_ci"], z["csat_test"])
    row("majority baseline, CSAT test MAE", bs["majority"]["mae"], bs["majority"]["n"], b["majority"]["mae"], b["majority"]["mae_ci"], z["csat_test"])
    for m in M:
        n = NICK[m]
        t = L[m]["csat"]["test"]
        k = keys(t)
        ch = L[m]["csat"]["chosen_on_dev"]
        s3 = P3[m]["csat"]["test_v3_after_calibration"]
        row(f"{n} CSAT, Phase 3 global map: QWK", s3["qwk"], s3["n"], t[k["before"]]["qwk"], t[k["before"]]["qwk_ci"], z["csat_test"])
        row(f"{n} CSAT, Phase 3 global map: MAE", s3["mae"], s3["n"], t[k["before"]]["mae"], t[k["before"]]["mae_ci"], z["csat_test"])
        p6 = P6[m]["delay_aware"]
        sk = p6["chosen_on_dev"]
        row(f"{n} CSAT, delay-aware after: QWK", p6["test"][sk]["metrics"]["qwk"], p6["test"][sk]["metrics"]["n"], t[ch]["qwk"], t[ch]["qwk_ci"], z["csat_test"])
        row(f"{n} CSAT, delay-aware after: MAE", p6["test"][sk]["metrics"]["mae"], p6["test"][sk]["metrics"]["n"], t[ch]["mae"], t[ch]["mae_ci"], z["csat_test"])
        row(f"{n} CSAT, delay-aware after: bucket-mean gap", p6["test"][sk]["bucket_gap"], p6["test"][sk]["metrics"]["n"], t[ch]["bucket_gap"], t[ch]["bucket_gap_ci"], z["csat_test"], 3)
        sb = p6["test"][sk]["by_delay"]["8 h+"]
        lb = t[ch]["by_bucket"]["8 h+"]
        row(f"{n} CSAT, delay-aware after: 8 h+ simulated mean (real: small {sb['real_mean']:.2f}, large {lb['real_mean']:.2f})",
            sb["sim_mean"], sb["n"], lb["sim_mean"], lb["sim_mean_ci"], lb["n"])
        cs = P3[m]["conv"]["test_chosen"]
        cl = L[m]["conv"]["chosen"]
        row(f"{n} CONV chosen version: QWK", cs["qwk"], cs["n"], cl["qwk"], cl["qwk_ci"], z["conv_test"])
        row(f"{n} CONV chosen version: MAE", cs["mae"], cs["n"], cl["mae"], cl["mae_ci"], z["conv_test"])
        fb6 = P6[m]["fallback"]
        g6 = next(k for k in fb6["olist_test"] if k.startswith("fallback global"))
        g7 = next(k for k in L[m]["fallback"]["olist_test"] if k.startswith("fallback global"))
        row(f"{n} fallback, Olist test QWK", fb6["olist_test"][g6]["qwk"], fb6["olist_test"][g6]["n"],
            L[m]["fallback"]["olist_test"][g7]["qwk"], L[m]["fallback"]["olist_test"][g7]["qwk_ci"], L[m]["fallback"]["olist_test"][g7]["n"])
        x6, x7 = fb6["on_flipkart_csat_test"]["metrics"], L[m]["fallback"]["on_csat_test"]["fallback"]
        row(f"{n} fallback on CSAT test: QWK", x6["qwk"], x6["n"], x7["qwk"], x7["qwk_ci"], x7["n"])
        row(f"{n} fallback on CSAT test: MAE", x6["mae"], x6["n"], x7["mae"], x7["mae_ci"], x7["n"])
    (RESULTS / "p7_tables.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
